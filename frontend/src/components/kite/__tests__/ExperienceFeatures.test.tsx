import React from 'react';
import {describe,it,expect,beforeEach,afterEach,vi} from 'vitest';
import {render,screen,fireEvent,cleanup,waitFor} from '@testing-library/react';
import {QueryClient,QueryClientProvider} from '@tanstack/react-query';
const get=vi.fn(),post=vi.fn(),patch=vi.fn(),put=vi.fn();
vi.mock('../../../utils/api',()=>({api:{get:(...a:unknown[])=>get(...a),post:(...a:unknown[])=>post(...a),patch:(...a:unknown[])=>patch(...a),put:(...a:unknown[])=>put(...a),delete:vi.fn()}}));
import {NavigationSettings} from '../NavigationSettings';
import {useExperienceOptions,readExperienceOptions,orderedNavigation} from '../../../store/useExperienceOptions';
import {ProfileMenu} from '../ProfileMenu';
import {FeedTestSettings} from '../FeedTestSettings';
import {PushSettings} from '../PushSettings';
const wrap=(child:React.ReactNode)=>render(<QueryClientProvider client={new QueryClient({defaultOptions:{queries:{retry:false}}})}>{child}</QueryClientProvider>);
beforeEach(()=>{localStorage.clear();useExperienceOptions.setState({options:readExperienceOptions()});get.mockReset();post.mockReset();patch.mockReset();put.mockReset();});afterEach(()=>{cleanup();vi.unstubAllGlobals();vi.restoreAllMocks();});
describe('Experience controls',()=>{
 it('hides and reorders navigation while keeping settings accessible',()=>{render(<NavigationSettings/>);fireEvent.click(screen.getByRole('checkbox',{name:'Astrology'}));expect(useExperienceOptions.getState().options.navHidden).toContain('astro');expect(screen.getByRole('checkbox',{name:'Settings'})).toBeDisabled();fireEvent.click(screen.getByRole('button',{name:'Move pcr up'}));expect(useExperienceOptions.getState().options.navOrder[1]).toBe('pcr');expect(orderedNavigation([{id:'astro'},{id:'pcr'}],useExperienceOptions.getState().options)).toEqual([{id:'pcr'}]);});
 it('opens the Sterling profile, not the broker identity, and does not mutate on render',async()=>{get.mockResolvedValue({username:'sterling-user',display_name:'Operator',photo:'',role:'user',user_id:'user'});wrap(<ProfileMenu/>);await screen.findByText('Operator');fireEvent.click(screen.getByRole('button',{name:'Sterling account profile'}));expect(await screen.findByRole('dialog',{name:'Sterling profile'})).toBeInTheDocument();expect(post).not.toHaveBeenCalled();expect(patch).not.toHaveBeenCalled();});
 it('edits a picture with a grid, circular preview and zoom before saving',async()=>{
  const profile={username:'sterling-user',display_name:'Operator',photo:'',role:'user',user_id:'user'};
  const encoded='data:image/jpeg;base64,/9j/AA==';
  get.mockResolvedValue(profile);patch.mockResolvedValue({...profile,photo:encoded});
  vi.stubGlobal('URL',class extends URL {
    static createObjectURL=vi.fn(()=>'blob:test-profile-crop');
    static revokeObjectURL=vi.fn();
  });
  const ctx={fillStyle:'',fillRect:vi.fn(),drawImage:vi.fn()};
  vi.spyOn(HTMLCanvasElement.prototype,'getContext').mockImplementation(()=>ctx as any);
  vi.spyOn(HTMLCanvasElement.prototype,'toDataURL').mockReturnValue(encoded);
  wrap(<ProfileMenu/>);
  await screen.findByText('Operator');
  fireEvent.click(screen.getByRole('button',{name:'Sterling account profile'}));
  expect(screen.getByRole('button',{name:'Add picture'})).toBeEnabled();
  expect(screen.getByRole('button',{name:'Remove picture'})).toBeDisabled();
  fireEvent.change(screen.getByLabelText('Choose profile picture'),{target:{files:[new File(['pixels'],'portrait.png',{type:'image/png'})]}});
  expect(await screen.findByRole('dialog',{name:'Crop profile picture'})).toBeInTheDocument();
  expect(screen.getByRole('group',{name:'Drag image to position profile picture'}).querySelectorAll('.sterling-crop-grid i')).toHaveLength(4);
  const cropImage=document.querySelector<HTMLImageElement>('.sterling-crop-image')!;
  await waitFor(()=>expect(cropImage).toHaveAttribute('src','blob:test-profile-crop'));
  Object.defineProperty(cropImage,'naturalWidth',{configurable:true,value:600});
  Object.defineProperty(cropImage,'naturalHeight',{configurable:true,value:400});
  fireEvent.load(cropImage);
  await waitFor(()=>expect(screen.getByRole('button',{name:'Use picture'})).toBeEnabled());
  expect(screen.getByRole('img',{name:'Circular profile preview'}).querySelector('img')).toHaveAttribute('src','blob:test-profile-crop');
  fireEvent.change(screen.getByRole('slider',{name:'Profile picture zoom'}),{target:{value:'1.5'}});
  expect(screen.getByText('1.50×')).toBeInTheDocument();
  expect(patch).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole('button',{name:'Use picture'}));
  expect(await screen.findByRole('dialog',{name:'Sterling profile'})).toBeInTheDocument();
  expect(screen.getByRole('img',{name:'Profile picture preview'})).toHaveAttribute('src',encoded);
  expect(screen.getByRole('button',{name:'Change picture'})).toBeEnabled();
  expect(patch).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole('button',{name:'Save profile'}));
  await waitFor(()=>expect(patch).toHaveBeenCalledWith('/api/v1/auth/profile',{display_name:'Operator',photo:encoded}));
  await waitFor(()=>expect(screen.getByRole('button',{name:'Sterling account profile'}).querySelector('img')).toHaveAttribute('src',encoded));
  expect(ctx.drawImage).toHaveBeenCalled();
 });
 it('cancels cropping without replacing the current picture',async()=>{
  const photo='data:image/jpeg;base64,/9j/AA==';
  get.mockResolvedValue({username:'sterling-user',display_name:'Operator',photo,role:'user',user_id:'user'});
  vi.stubGlobal('URL',class extends URL {
    static createObjectURL=vi.fn(()=>'blob:test-cancel');
    static revokeObjectURL=vi.fn();
  });
  wrap(<ProfileMenu/>);await screen.findByText('Operator');
  fireEvent.click(screen.getByRole('button',{name:'Sterling account profile'}));
  fireEvent.change(screen.getByLabelText('Choose profile picture'),{target:{files:[new File(['new'],'replacement.png',{type:'image/png'})]}});
  expect(await screen.findByRole('dialog',{name:'Crop profile picture'})).toBeInTheDocument();
  fireEvent.click(screen.getByRole('button',{name:'Cancel'}));
  expect(await screen.findByRole('dialog',{name:'Sterling profile'})).toBeInTheDocument();
  expect(screen.getByRole('img',{name:'Profile picture preview'})).toHaveAttribute('src',photo);
  expect(patch).not.toHaveBeenCalled();
 });
 it('removes a saved profile picture only after Save profile',async()=>{
  const photo='data:image/jpeg;base64,/9j/AA==';
  const profile={username:'sterling-user',display_name:'Operator',photo,role:'user',user_id:'user'};
  get.mockResolvedValue(profile);patch.mockResolvedValue({...profile,photo:''});
  wrap(<ProfileMenu/>);await screen.findByText('Operator');
  fireEvent.click(screen.getByRole('button',{name:'Sterling account profile'}));
  expect(screen.getByRole('img',{name:'Profile picture preview'})).toHaveAttribute('src',photo);
  fireEvent.click(screen.getByRole('button',{name:'Remove picture'}));
  expect(screen.getByRole('img',{name:'No profile picture'})).toBeInTheDocument();
  expect(patch).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole('button',{name:'Save profile'}));
  await waitFor(()=>expect(patch).toHaveBeenCalledWith('/api/v1/auth/profile',{display_name:'Operator',photo:''}));
  await waitFor(()=>expect(screen.getByRole('button',{name:'Sterling account profile'}).querySelector('img')).toBeNull());
 });
 it('rejects unsupported and oversized profile pictures without changing the preview',async()=>{
  get.mockResolvedValue({username:'operator',display_name:'Operator',photo:'',role:'user',user_id:'user'});
  wrap(<ProfileMenu/>);await screen.findByText('Operator');
  fireEvent.click(screen.getByRole('button',{name:'Sterling account profile'}));
  const input=screen.getByLabelText('Choose profile picture');
  fireEvent.change(input,{target:{files:[new File(['<svg />'],'unsafe.svg',{type:'image/svg+xml'})]}});
  expect(await screen.findByText('Choose a PNG, JPEG or WebP up to 10 MB.')).toBeInTheDocument();
  fireEvent.change(input,{target:{files:[new File(['x'.repeat(10000001)],'large.png',{type:'image/png'})]}});
  expect(screen.getByRole('img',{name:'No profile picture'})).toBeInTheDocument();
  expect(patch).not.toHaveBeenCalled();
 });
 it('tests only the exact selected provider symbol',async()=>{get.mockResolvedValue({confirmed:null});post.mockResolvedValue({id:'probe',provider:'kite',symbol:'NSE:NIFTY 50',price:100,quote_time:null,observed_at:'now',age_seconds:null,latency_ms:30,market_phase:'closed',freshness:'provider timestamp unavailable',realtime_verified:false,note:'read-only'});wrap(<FeedTestSettings/>);fireEvent.change(screen.getByRole('textbox',{name:'Feed test symbol'}),{target:{value:'NSE:NIFTY 50'}});fireEvent.click(screen.getByRole('button',{name:'Fetch test quote'}));await waitFor(()=>expect(post).toHaveBeenCalledWith('/api/v1/auth/feed-test/probe',{provider:'kite',symbol:'NSE:NIFTY 50'}));expect(await screen.findByText('No — see timestamp and provider limits')).toBeInTheDocument();});
 it('does not request push permission or send a test just by opening settings',async()=>{get.mockResolvedValue({public_key:'key',config:{enabled:false,signals:true,pcr:true,alerts:true,quiet_enabled:false,quiet_start:'22:00',quiet_end:'08:00',private_preview:true,max_per_hour:12},devices:[]});wrap(<PushSettings/>);expect(await screen.findByText('No registered devices.')).toBeInTheDocument();expect(post).not.toHaveBeenCalled();expect(put).not.toHaveBeenCalled();});
});
